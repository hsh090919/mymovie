def get_korea_dates():
    """
    배포 서버가 어느 나라에 있더라도
    한국 시간(Asia/Seoul)을 기준으로 날짜를 계산합니다.

    반환값:
    - today: 한국 시간 기준 오늘
    - yesterday: 한국 시간 기준 어제
    """

    korea_now = datetime.now(
        ZoneInfo("Asia/Seoul")
    )

    today = korea_now.date()

    yesterday = today - timedelta(days=1)

    return today, yesterday


