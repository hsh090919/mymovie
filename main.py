def format_rank_change(value):
    """
    rankInten 값을 보기 쉽게 표시합니다.

    양수:
    🔺 빨간 위 화살표

    음수:
    🔻 파란 아래 화살표

    0:
    ➖ 변동 없음
    """

    # 값이 없는 경우
    if pd.isna(value):

        return "-"


    # 양수
    if value > 0:

        return f"🔺 {int(value)}"


    # 음수
    elif value < 0:

        return f"🔻 {abs(int(value))}"


    # 0
    else:

        return "➖ 0"


# =========================================================
# 영화명에 트로피 추가 함수
# =========================================================

def add_trophy(movie_name, audience_acc):
    """
    누적관객이 100만 명을 넘은 영화는
    영화명 뒤에 트로피 이모지를 붙입니다.
    """

    if pd.notna(audience_acc):

        if audience_acc > 1_000_000:

            return f"{movie_name} 🏆"


    return movie_name


