@st.cache_data(ttl=3600)
def get_daily_boxoffice(target_date, api_key):
    """
    선택한 날짜의 박스오피스 데이터를 가져옵니다.

    같은 날짜를 다시 조회하면
    1시간 동안 이전 결과를 재사용합니다.

    target_date: yyyymmdd 형식의 날짜
    api_key: KOBIS 인증키
    """

    # KOBIS 일별 박스오피스 API 주소
    url = (
        "https://www.kobis.or.kr/"
        "kobisopenapi/webservice/rest/boxoffice/"
        "searchDailyBoxOfficeList.json"
    )

    # API 요청 파라미터
    params = {
        "key": api_key,
        "targetDt": target_date
    }

    # =====================================================
    # API 요청
    # =====================================================

    try:

        response = requests.get(
            url,
            params=params,
            timeout=15
        )

    except requests.exceptions.RequestException as e:

        raise RuntimeError(
            "KOBIS API 서버에 연결하지 못했습니다.\n\n"
            f"네트워크 오류: {e}"
        )


    # =====================================================
    # HTTP 상태 코드 확인
    # =====================================================

    if response.status_code != 200:

        raise RuntimeError(
            "KOBIS API 요청에 실패했습니다.\n\n"
            f"HTTP 상태 코드: {response.status_code}"
        )


    # =====================================================
    # JSON 데이터로 변환
    # =====================================================

    try:

        data = response.json()

    except ValueError:

        raise RuntimeError(
            "KOBIS API가 정상적인 JSON 데이터를 반환하지 않았습니다."
        )


    # =====================================================
    # KOBIS faultInfo 오류 확인
    # =====================================================

    # KOBIS API는 인증키가 잘못되어도
    # HTTP 상태 코드 200을 반환할 수 있으므로
    # faultInfo를 별도로 확인해야 합니다.

    if "faultInfo" in data:

        fault = data["faultInfo"]

        # 오류 코드
        error_code = fault.get(
            "errorCode",
            "확인할 수 없음"
        )

        # 오류 메시지
        error_message = fault.get(
            "message",
            fault.get(
                "messageId",
                "오류 메시지가 제공되지 않았습니다."
            )
        )

        raise RuntimeError(
            "KOBIS API에서 오류를 반환했습니다.\n\n"
            f"오류 코드: {error_code}\n"
            f"오류 메시지: {error_message}"
        )


    # =====================================================
    # boxOfficeResult 확인
    # =====================================================

    if "boxOfficeResult" not in data:

        raise RuntimeError(
            "API 응답에 boxOfficeResult가 없습니다."
        )


    boxoffice_result = data["boxOfficeResult"]


    # =====================================================
    # 영화 목록 가져오기
    # =====================================================

    movie_list = boxoffice_result.get(
        "dailyBoxOfficeList",
        []
    )


    # =====================================================
    # 영화 목록이 비어 있는 경우
    # =====================================================

    # 빈 목록 자체는 API 오류가 아닙니다.
    # 화면에서 "그날은 아직 집계 전입니다"라고
    # 안내할 수 있도록 빈 리스트를 그대로 반환합니다.

    return movie_list


